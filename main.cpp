/**
 * @file main.cpp
 * @brief Демонстрация работы класса Movie.
 *
 * Программа создаёт объекты класса Movie с использованием
 * разных конструкторов, проверяет корректные и некорректные
 * операции изменения состояния, а также демонстрирует
 * независимость объектов и работу статического счётчика.
 *
 * @author Куртнебиев Р.Р.
 * @date 05.10.2026
 */

#include <iostream>
#include <iomanip>
#include <string>

#include "Movie.h"

/**
 * @brief Главная функция программы.
 *
 * Создаёт несколько объектов класса Movie и проверяет работу
 * конструкторов, методов изменения данных, проверки некорректных
 * значений, независимости объектов и счётчика объектов.
 *
 * @return 0 при успешном завершении программы.
 */
int main()
{
    std::cout << std::fixed << std::setprecision(1);

    std::cout << "=== СОЗДАНИЕ ОБЪЕКТОВ ===\n\n";

    /**
     * @brief Создание первого фильма конструктором по умолчанию.
     */
    Movie movie1;

    /**
     * @brief Создание второго фильма параметризованным конструктором.
     */
    Movie movie2(
        "Интерстеллар",
        2014,
        8.7,
        Genre::SciFi,
        169
    );

    /**
     * @brief Создание третьего фильма с помощью конструктора копирования.
     */
    Movie movie3(movie2);

    std::cout << "Количество существующих объектов: "
              << Movie::getObjectCount() << "\n\n";

    std::cout << "=== НАЧАЛЬНОЕ СОСТОЯНИЕ ===\n\n";

    std::cout << "Фильм 1:\n";
    movie1.printInfo();

    std::cout << "\nФильм 2:\n";
    movie2.printInfo();

    std::cout << "\nФильм 3:\n";
    movie3.printInfo();

    std::cout << "\n=== КОРРЕКТНЫЕ ОПЕРАЦИИ ===\n\n";

    /**
     * @brief Проверка корректного изменения данных первого фильма.
     */
    movie1.changeTitle("Начало");
    movie1.changeRating(8.8);
    movie1.changeDuration(148);

    std::cout << "После изменения фильма 1:\n";
    movie1.printInfo();

    std::cout << "\n=== НЕКОРРЕКТНЫЕ ОПЕРАЦИИ ===\n\n";

    /**
     * @brief Проверка запрета пустого названия.
     */
    if (!movie1.changeTitle(""))
    {
        std::cout << "Ошибка: нельзя установить пустое название.\n";
    }

    /**
     * @brief Проверка запрета рейтинга больше 10.
     */
    if (!movie1.changeRating(15.0))
    {
        std::cout << "Ошибка: рейтинг не может быть больше 10.\n";
    }

    /**
     * @brief Проверка запрета отрицательного рейтинга.
     */
    if (!movie1.changeRating(-2.0))
    {
        std::cout << "Ошибка: рейтинг не может быть отрицательным.\n";
    }

    /**
     * @brief Проверка запрета нулевой продолжительности.
     */
    if (!movie1.changeDuration(0))
    {
        std::cout << "Ошибка: продолжительность должна быть больше 0.\n";
    }

    std::cout << "\n=== СОСТОЯНИЕ ПОСЛЕ НЕКОРРЕКТНЫХ ОПЕРАЦИЙ ===\n\n";

    movie1.printInfo();

    std::cout << "\n=== ПРОВЕРКА НЕЗАВИСИМОСТИ ОБЪЕКТОВ ===\n\n";

    std::cout << "Фильм 2 до изменения:\n";
    movie2.printInfo();

    std::cout << "\nИзменяем только фильм 2...\n\n";

    movie2.changeTitle("Интерстеллар: Новая версия");
    movie2.changeRating(9.0);

    std::cout << "Фильм 2 после изменения:\n";
    movie2.printInfo();

    std::cout << "\nФильм 3 после изменения фильма 2:\n";
    movie3.printInfo();

    std::cout << "\n=== ПРОВЕРКА КОНСТРУКТОРА КОПИРОВАНИЯ ===\n\n";

    std::cout << "Фильм 2 и фильм 3 были созданы как отдельные объекты.\n";
    std::cout << "Изменение фильма 2 не изменило фильм 3.\n";

    std::cout << "\n=== КОНЕЦ ПРОГРАММЫ ===\n";

    std::cout << "Количество объектов перед завершением main(): "
              << Movie::getObjectCount() << '\n';

    return 0;
}